#include <pdfio.h>
#include <pdfio-content.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>


// Fail on PDFio diagnostics, including recovery of damaged xref offsets.
static bool
pdf_error(pdfio_file_t *pdf, const char *message, void *data)
{
  int *errors = data;

  (void)pdf;
  (*errors) ++;
  fprintf(stderr, "%s\n", message);
  return (false);
}


static int
create_fixture(const char *filename)
{
  pdfio_rect_t media = { 0, 0, 595, 842 };
  pdfio_file_t *pdf;
  pdfio_obj_t *font;
  int page;
  int errors = 0;

  if ((pdf = pdfioFileCreate(filename, "1.7", &media, &media,
                            pdf_error, &errors)) == NULL)
    return (1);
  font = pdfioFileCreateFontObjFromBase(pdf, "Helvetica");
  for (page = 1; page <= 4; page ++)
  {
    pdfio_dict_t *dict = pdfioDictCreate(pdf);
    pdfio_stream_t *st;

    if (!font || !dict || !pdfioPageDictAddFont(dict, "F1", font) ||
        (st = pdfioFileCreatePage(pdf, dict)) == NULL)
      return (1);
    pdfioContentTextBegin(st);
    pdfioContentSetTextFont(st, "F1", 24);
    pdfioContentTextMoveTo(st, 72, 720);
    pdfioContentTextShowf(st, false, "Page %d", page);
    pdfioContentTextEnd(st);
    if (!pdfioStreamClose(st))
      return (1);
  }
  return (!pdfioFileClose(pdf) || errors);
}


static int
check_output(const char *filename, const char *expected)
{
  FILE *fp;
  char buf[4096];
  int line, generated = 0, copies = 0, collate = 0;
  int errors = 0;
  size_t page, count = 1;
  const char *p;
  pdfio_file_t *pdf;

  if ((fp = fopen(filename, "rb")) == NULL)
    return (1);
  if (!fgets(buf, sizeof(buf), fp) || strcmp(buf, "%PDF-1.7\n"))
    return (1);

  // libppd 2.1.1's parse_pdftopdf_comment() scans only these 20 lines.
  // Check the complete legacy spelling and values, including the space
  // before ':'. Copies are already expanded into the output page sequence.
  for (line = 0; line < 20 && fgets(buf, sizeof(buf), fp); line ++)
  {
    if (line == 0 && (buf[0] != '%' || strlen(buf) < 5 ||
                     (unsigned char)buf[1] < 128 ||
                     (unsigned char)buf[2] < 128 ||
                     (unsigned char)buf[3] < 128 ||
                     (unsigned char)buf[4] < 128))
    {
      fputs("Missing binary-data comment on the second line.\n", stderr);
      return (1);
    }
    generated += !strcmp(buf, "% This file was generated by pdftopdf\n");
    copies += !strcmp(buf, "%%PDFTOPDFNumCopies : 1\n");
    collate += !strcmp(buf, "%%PDFTOPDFCollate : false\n");
  }
  fclose(fp);
  if (generated != 1 || copies != 1 || collate != 1)
  {
    fputs("Missing or incorrect PDFTOPDF header comments.\n", stderr);
    return (1);
  }

  if ((pdf = pdfioFileOpen(filename, NULL, NULL, pdf_error, &errors)) == NULL)
    return (1);
  for (p = expected; *p; p ++)
    if (*p == ',')
      count ++;
  if (pdfioFileGetNumPages(pdf) != count)
  {
    fprintf(stderr, "Expected %u pages, got %u.\n", (unsigned)count,
            (unsigned)pdfioFileGetNumPages(pdf));
    return (1);
  }

  // Each comma-separated group lists the source pages on that output page.
  // This checks selection, N-up placement and the software copy order.
  for (page = 0, p = expected; page < count; page ++)
  {
    pdfio_obj_t *obj = pdfioFileGetPage(pdf, page);
    size_t stream;
    unsigned wanted = 0, found = 0;

    for (; *p && *p != ','; p ++)
      wanted |= 1U << (*p - '1');
    if (*p)
      p ++;
    for (stream = 0; stream < pdfioPageGetNumStreams(obj); stream ++)
    {
      pdfio_stream_t *st = pdfioPageOpenStream(obj, stream, true);

      if (!st)
        return (1);
      while (pdfioStreamGetToken(st, buf, sizeof(buf)))
      {
        int source;
        if (sscanf(buf, "(Page %d", &source) == 1 && source >= 1 && source <= 4)
          found |= 1U << (source - 1);
      }
      if (!pdfioStreamClose(st))
        return (1);
    }
    if (found != wanted)
    {
      fprintf(stderr, "Wrong source pages on output page %u: %x != %x.\n",
              (unsigned)page + 1, found, wanted);
      return (1);
    }
  }
  return (!pdfioFileClose(pdf) || errors);
}


int
main(int argc, char *argv[])
{
  if (argc == 3 && !strcmp(argv[1], "--create"))
    return (create_fixture(argv[2]));
  if (argc == 3)
    return (check_output(argv[1], argv[2]));
  fputs("Usage: check --create INPUT.pdf | check OUTPUT.pdf PAGE-GROUPS\n", stderr);
  return (1);
}
